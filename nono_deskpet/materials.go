// 合成时真实扣除，形成「选模板 → 摆材料 → 开始合成」的完整流程。

// materialDef 一种材料道具的定义。
type materialDef struct {
	ID   int
	Name string
}

// materialDefs 12 种材料，顺序即储藏页与选择菜单里的展示顺序。
// 说明：2026-10-23 起材料改为**无限使用**（不扣库存），Materials 字段只保留
// 「是否拥有该材料」的存档占位，不再递减。
var materialDefs = []materialDef{
	{400001, "黄晶矿"},
	{400002, "甲烷燃气"},
	{400003, "玄冰"},
	{400004, "空气结晶"},
	{400005, "光合能量"},
	{400006, "水之精华"},
	{400007, "火焰元素"},
	{400008, "电容球"},
	{400009, "藤结晶"},
	{400010, "蘑菇结晶"},
	{400012, "豆豆果实"},
	{400026, "希欧珊瑚"},
}

// defaultMaterialCount 每种材料的初始数量。材料已改为无限使用，这个值只作为
// 存档占位（旧档里被扣过的数字不影响合成）。
const defaultMaterialCount = 20

// defaultMaterials 生成初始材料库存。
func defaultMaterials() map[int]int {
	m := make(map[int]int, len(materialDefs))
	for _, d := range materialDefs {
		m[d.ID] = defaultMaterialCount
	}
	return m
}

// ensureMaterials 旧存档没有 materials 字段时补一份，避免升级后合成面板空着。
func (s *Save) ensureMaterials() {
	if len(s.Materials) > 0 {
		return
	}
	s.Materials = defaultMaterials()
}

// materialName 返回材料名，未知 ID 返回空串。
func materialName(id int) string {
	for _, d := range materialDefs {
		if d.ID == id {
			return d.Name
		}
	}
	return ""
}

// isMaterial 判断 ID 是否为材料道具（材料都是 4000xx，芯片都是 700xxx）。
func isMaterial(id int) bool {
	return id >= 400000 && id < 500000
}

